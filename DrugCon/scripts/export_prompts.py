"""Render every prompt template into docs/prompts.md so the docs never drift
from the code.

    python scripts/export_prompts.py
"""
from __future__ import annotations

from drugcon import paths
from drugcon.prompts import DETECTION_PROMPTS, EXPLANATION_PROMPTS, SYSTEM_PROMPT

HEADER = """# Prompt templates

This file is generated by `scripts/export_prompts.py` from `src/drugcon/prompts.py`.
Do not edit by hand.

Every request uses the system message:

```text
{system}
```

(For models whose API rejects a system message, e.g. Mistral-7B on Bedrock, it
is prepended to the user turn.)

## Which prompt backs which result

| Result | Prompt alias | Version id (in run filenames) |
| --- | --- | --- |
| Table 2, DrugCon detection (GPT-4.1-nano) | `counterfactual` | `counterfactual_appendix_v2` |
| Table 3, detection CF column, GPT-4.1-nano | `counterfactual` | `counterfactual_appendix_v2` |
| Table 3, detection CF column, all other backbones | `counterfactual_strict` | `counterfactual_appendix_v1` |
| Table 3, detection DC column | `direct` | `drug_disease_claim_only_v2` |
| Table 3 explanation and Table C1, all backbones except GPT-4.1-nano | `taxonomy` | `taxonomy_v1` |
| Table 3 explanation and Table C1, GPT-4.1-nano | original pipeline run | `drugcon_pipeline_v1` |

`results/tables/paper/table3_ablation_sources.csv` lists the exact run used for
every cell.

"""


def section(title: str, registry: dict, placeholders: tuple) -> str:
    out = [f"## {title}\n"]
    for spec in registry.values():
        out.append(f"### `{spec.alias}` (`{spec.version}`)\n\n{spec.description}\n")
        out.append("```text\n" + spec.builder(*placeholders) + "\n```\n")
    return "\n".join(out)


def main() -> None:
    text = HEADER.format(system=SYSTEM_PROMPT)
    text += section("Detection prompts", DETECTION_PROMPTS, ("{claim_1}", "{claim_2}"))
    text += "\n" + section("Explanation prompts", EXPLANATION_PROMPTS,
                           ("{claim_1}", "{abstract_1}", "{claim_2}", "{abstract_2}"))
    out = paths.REPO_ROOT / "docs" / "prompts.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
