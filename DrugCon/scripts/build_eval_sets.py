"""Freeze the evaluation sets from the DrugCon-Bench release files.

detection.csv    Closed-world detection set: every candidate claim pair produced
                 by claim pairing over the 819 benchmark abstracts. A pair is
                 positive iff it is one of the annotated contradictory pairs.
explanation.csv  The annotated contradictory pairs with their gold study-level
                 factor labels and both source abstracts.

The output is deterministic; re-running it is a no-op unless the benchmark
files change. PROVENANCE.txt records source checksums and set sizes.

    python scripts/build_eval_sets.py
"""
from __future__ import annotations

import hashlib

import pandas as pd

from drugcon import paths
from drugcon.evaluation import NEGATIVE, POSITIVE
from drugcon.runs import pair_key


def _md5(path) -> str:
    return hashlib.md5(path.read_bytes()).hexdigest()


def main() -> None:
    paths.EVAL_DIR.mkdir(parents=True, exist_ok=True)
    gold = pd.read_csv(paths.GOLD_PAIRS)
    cand = pd.read_csv(paths.CANDIDATE_PAIRS)

    # ---- explanation set: gold contradictory pairs ----
    explanation = gold[["id", "pmid_1", "pmid_2", "claim_1", "claim_2",
                        "claim_abs_1", "claim_abs_2", "human_labeled_contextual_factors"]].copy()
    explanation.to_csv(paths.EXPLANATION_SET, index=False)

    # ---- detection set: closed-world candidate universe ----
    gold_keys = {pair_key(a, b) for a, b in zip(gold.claim_1, gold.claim_2)}
    cand["pair_key"] = [pair_key(a, b) for a, b in zip(cand.claim_1, cand.claim_2)]
    if not cand["pair_key"].is_unique:
        raise ValueError("candidate_pairs.csv contains duplicate claim pairs")
    cand["gold_label"] = [POSITIVE if k in gold_keys else NEGATIVE for k in cand.pair_key]

    missing = gold_keys - set(cand.pair_key)
    if missing:
        raise ValueError(f"{len(missing)} gold pairs are absent from candidate_pairs.csv")

    detection = cand[["pair_id", "pmid_1", "pmid_2", "claim_1", "claim_2", "pair_key", "gold_label"]]
    detection.to_csv(paths.DETECTION_SET, index=False)

    n_pos = int((detection.gold_label == POSITIVE).sum())
    provenance = (
        "Frozen evaluation sets for DrugCon-Bench (generated by scripts/build_eval_sets.py)\n"
        f"source: data/drugcon_bench/contradictory_claim_pairs.csv  md5={_md5(paths.GOLD_PAIRS)}\n"
        f"source: data/drugcon_bench/candidate_pairs.csv            md5={_md5(paths.CANDIDATE_PAIRS)}\n"
        f"\ndetection.csv:   {len(detection)} candidate pairs, "
        f"{n_pos} positive / {len(detection) - n_pos} negative\n"
        f"explanation.csv: {len(explanation)} gold contradictory pairs\n"
        "\nManConCorpus (external generalisation test) is not redistributed here;\n"
        "see data/README.md for how it was converted and split.\n"
    )
    (paths.EVAL_DIR / "PROVENANCE.txt").write_text(provenance)
    print(provenance)


if __name__ == "__main__":
    main()
